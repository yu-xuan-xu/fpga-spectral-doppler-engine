#!/usr/bin/env python3
"""Generate deterministic Q1.15 twiddle ROM and FFT simulation input."""

from pathlib import Path

import numpy as np
from doppler.fixed import quantize_q15


def sv_signed(value: int) -> str:
    return f"-16'sd{abs(value)}" if value < 0 else f"16'sd{value}"


def main() -> None:
    root = Path(__file__).resolve().parents[1]
    include = root / "rtl" / "core" / "fft_twiddle_q15.svh"
    with include.open("w", encoding="ascii") as stream:
        stream.write("// Generated by scripts/generate_fft_assets.py\n")
        stream.write("function automatic logic signed [15:0] twiddle_re(input logic [6:0] k);\n")
        stream.write("  case (k)\n")
        for k in range(128):
            value = int(quantize_q15([np.cos(-2 * np.pi * k / 256)])[0])
            stream.write(f"    7'd{k}: twiddle_re = {sv_signed(value)};\n")
        stream.write("    default: twiddle_re = '0;\n  endcase\nendfunction\n")
        stream.write("function automatic logic signed [15:0] twiddle_im(input logic [6:0] k);\n")
        stream.write("  case (k)\n")
        for k in range(128):
            value = int(quantize_q15([np.sin(-2 * np.pi * k / 256)])[0])
            stream.write(f"    7'd{k}: twiddle_im = {sv_signed(value)};\n")
        stream.write("    default: twiddle_im = '0;\n  endcase\nendfunction\n")

    vector = root / "tb" / "sv" / "fft_tone_bin16.mem"
    n = np.arange(256)
    tone = 0.5 * np.exp(2j * np.pi * 16 * n / 256)
    i_values, q_values = quantize_q15(tone.real), quantize_q15(tone.imag)
    with vector.open("w", encoding="ascii") as stream:
        for i_value, q_value in zip(i_values, q_values, strict=True):
            packed = ((int(i_value) & 0xFFFF) << 16) | (int(q_value) & 0xFFFF)
            stream.write(f"{packed:08x}\n")

    hann = root / "rtl" / "core" / "hann_q15.svh"
    coefficients = np.floor(np.hanning(256) * 32767.0 + 0.5).astype(int)
    coefficients[0] = coefficients[-1] = 0
    with hann.open("w", encoding="ascii") as stream:
        stream.write("// Generated by scripts/generate_fft_assets.py\n")
        stream.write("function automatic logic [15:0] hann_coeff(input logic [7:0] k);\n")
        stream.write("  case (k)\n")
        for k, value in enumerate(coefficients):
            stream.write(f"    8'd{k}: hann_coeff = 16'd{value};\n")
        stream.write("    default: hann_coeff = '0;\n  endcase\nendfunction\n")


if __name__ == "__main__":
    main()
